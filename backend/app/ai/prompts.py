"""Шаблоны промптов AI-слоя (интерпретация показателей и рекомендации)."""

from __future__ import annotations

SYSTEM_PROMPT = (
    "Ты аналитик отдела маркетинга. По сводным данным сквозной аналитики находи "
    "закономерности, отклонения и риски, не видимые из обычных статистических "
    "показателей. Пиши кратко, по-русски, без выдуманных чисел — только на основе "
    "переданных данных. Не давай прямых указаний по изменению рекламных кабинетов."
)


def insights_prompt(summary: dict) -> str:
    """Промпт для генерации инсайтов по сводке аналитики."""
    return (
        "Сводка по каналам, кампаниям и воронке:\n"
        f"{summary}\n\n"
        "Сформируй до 5 инсайтов. Для каждого укажи: заголовок, что видно на "
        "дашборде, объяснение, рекомендацию, источники данных и достоверность."
    )


def deal_comment_prompt(deal: dict) -> str:
    """Промпт для короткого комментария AI по сделке/лиду."""
    return (
        "Данные сделки:\n"
        f"{deal}\n\n"
        "Дай короткий комментарий (1 предложение) о риске или точке внимания."
    )
